internal fun rebalanceLastChunk(chunks: MutableList<MutableList<String>>) {
    if (chunks.size < 2) return
    val last = chunks.last()
    while (modelHeader().lineCount() + last.sumOf(String::lineCount) < MIN_GENERATED_LINES) {
        val previous = chunks[chunks.lastIndex - 1]
        val moved = previous.lastOrNull() ?: break
        val previousAfterMove = modelHeader().lineCount() + previous.dropLast(1).sumOf(String::lineCount)
        val lastAfterMove = modelHeader().lineCount() + last.sumOf(String::lineCount) + moved.lineCount()
        if (previousAfterMove < MIN_GENERATED_LINES || lastAfterMove > MAX_GENERATED_LINES) break
        previous.removeLast()
        last.add(0, moved)
    }
    val lastLines = modelHeader().lineCount() + last.sumOf(String::lineCount)
    if (lastLines >= MIN_GENERATED_LINES) return
    val previous = chunks[chunks.lastIndex - 1]
    val mergedLines = modelHeader().lineCount() + previous.sumOf(String::lineCount) + last.sumOf(String::lineCount)
    check(mergedLines <= MAX_GENERATED_LINES) { "Unable to create a model shard of at least $MIN_GENERATED_LINES lines" }
    previous += last
    chunks.removeLast()
}

internal fun writeGeneratedSources(directory: File, sources: List<GeneratedFile>) {
    val desired = sources.map(GeneratedFile::name).toSet()
    sources.forEach { source -> writeText(directory.resolve(source.name), source.content.trimEnd() + "\n") }
    directory.listFiles().orEmpty()
        .filter { it.name.startsWith("GeneratedProtocol") && it.extension == "kt" && it.name !in desired }
        .forEach { check(it.delete()) { "Unable to delete stale generated source ${it.path}" } }
}

internal fun String.lineCount(): Int = lineSequence().count()

internal const val MIN_GENERATED_LINES = 100
internal const val PREFERRED_GENERATED_LINES = 220
internal const val MAX_GENERATED_LINES = 300
internal const val MODEL_HEADER_LINES = 14

internal fun provenanceInput(path: String, gitBlob: String, file: File) = buildJsonObject {
    put("path", path)
    put("gitBlob", gitBlob)
    put("sha256", file.sha256())
}

internal fun writeText(file: File, value: String) {
    writeBytes(file, value.toByteArray())
}

internal fun writeBytes(file: File, value: ByteArray) {
    file.parentFile.mkdirs()
    val temporary = File(file.parentFile, ".${file.name}.next")
    temporary.writeBytes(value)
    check(temporary.renameTo(file) || (file.delete() && temporary.renameTo(file))) {
        "Unable to replace ${file.path}"
    }
}

internal fun File.sha256(): String = inputStream().use { input ->
    val digest = MessageDigest.getInstance("SHA-256")
    val buffer = ByteArray(DEFAULT_BUFFER_SIZE)
    while (true) {
        val count = input.read(buffer)
        if (count < 0) break
        digest.update(buffer, 0, count)
    }
    digest.digest().joinToString("") { "%02x".format(it.toInt() and 0xff) }
}

internal fun String.escape(): String = replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

internal fun String.kotlinTypeName(): String = split(Regex("[^A-Za-z0-9]+")).filter(String::isNotEmpty)
    .joinToString("") { part -> part.replaceFirstChar(Char::uppercase) }
    .let { if (it.firstOrNull()?.isDigit() == true) "Method$it" else it }
